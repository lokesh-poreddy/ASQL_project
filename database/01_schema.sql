-- ── authors ──────────────────────────────────────────────────────────────────
CREATE TABLE authors (
    author_id        NUMBER GENERATED BY DEFAULT AS IDENTITY
                         CONSTRAINT pk_authors PRIMARY KEY,
    full_name        VARCHAR2(500 CHAR)  NOT NULL,
    normalized_name  VARCHAR2(500 CHAR)  NOT NULL,
    affiliation      VARCHAR2(500 CHAR),
    orcid            VARCHAR2(40),
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ── venues ────────────────────────────────────────────────────────────────────
CREATE TABLE venues (
    venue_id    NUMBER GENERATED BY DEFAULT AS IDENTITY
                    CONSTRAINT pk_venues PRIMARY KEY,
    venue_name  VARCHAR2(500 CHAR) NOT NULL,
    venue_type  VARCHAR2(30)       NOT NULL,   -- CONFERENCE | JOURNAL | WORKSHOP | PREPRINT_SERVER
    issn        VARCHAR2(20),
    publisher   VARCHAR2(300 CHAR),
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ── research_areas ───────────────────────────────────────────────────────────
CREATE TABLE research_areas (
    area_id        NUMBER GENERATED BY DEFAULT AS IDENTITY
                       CONSTRAINT pk_research_areas PRIMARY KEY,
    area_name      VARCHAR2(250 CHAR) NOT NULL,
    parent_area_id NUMBER,                     -- self-referencing hierarchy
    description    VARCHAR2(1000 CHAR)
);

-- ── keywords ─────────────────────────────────────────────────────────────────
CREATE TABLE keywords (
    keyword_id   NUMBER GENERATED BY DEFAULT AS IDENTITY
                     CONSTRAINT pk_keywords PRIMARY KEY,
    keyword_text VARCHAR2(250 CHAR) NOT NULL
);

-- ── papers ───────────────────────────────────────────────────────────────────
CREATE TABLE papers (
    paper_id                NUMBER GENERATED BY DEFAULT AS IDENTITY
                                CONSTRAINT pk_papers PRIMARY KEY,
    paper_code              VARCHAR2(50)        NOT NULL,   -- e.g. P-00001
    title                   VARCHAR2(1000 CHAR) NOT NULL,
    abstract                CLOB,
    year                    NUMBER(4)           NOT NULL,
    venue_id                NUMBER,
    citation_count          NUMBER DEFAULT 0    NOT NULL,
    primary_research_area_id NUMBER,
    doi                     VARCHAR2(500),
    publication_type        VARCHAR2(30),                   -- ARTICLE | CONFERENCE_PAPER | PREPRINT
    extra_metadata          JSON,
    created_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ── paper_authors (junction) ─────────────────────────────────────────────────
CREATE TABLE paper_authors (
    paper_id     NUMBER NOT NULL,
    author_id    NUMBER NOT NULL,
    author_order NUMBER NOT NULL,
    CONSTRAINT pk_paper_authors PRIMARY KEY (paper_id, author_id)
);

-- ── paper_keywords (junction) ────────────────────────────────────────────────
CREATE TABLE paper_keywords (
    paper_id   NUMBER NOT NULL,
    keyword_id NUMBER NOT NULL,
    CONSTRAINT pk_paper_keywords PRIMARY KEY (paper_id, keyword_id)
);

-- ── citations (paper → paper) ────────────────────────────────────────────────
CREATE TABLE citations (
    citation_id      NUMBER GENERATED BY DEFAULT AS IDENTITY
                         CONSTRAINT pk_citations PRIMARY KEY,
    citing_paper_id  NUMBER NOT NULL,
    cited_paper_id   NUMBER NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ── paper_embeddings ─────────────────────────────────────────────────────────
-- Actual VECTOR columns are added by 07_vector.sql after version check.
-- This table stores metadata + the compressed representations.
CREATE TABLE paper_embeddings (
    embedding_id          NUMBER GENERATED BY DEFAULT AS IDENTITY
                              CONSTRAINT pk_paper_embeddings PRIMARY KEY,
    paper_id              NUMBER        NOT NULL,
    model_name            VARCHAR2(200) NOT NULL,
    precision_mode        VARCHAR2(10)  NOT NULL,   -- FP32 | FP16 | INT8
    dimension             NUMBER        NOT NULL,
    -- VECTOR columns added by 07_vector.sql
    embedding_f16_emulated RAW(768),               -- FP16 stored as RAW until native support
    quantization_scale    BINARY_DOUBLE,
    source_text           CLOB,
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ── query_history ────────────────────────────────────────────────────────────
CREATE TABLE query_history (
    history_id            NUMBER GENERATED BY DEFAULT AS IDENTITY
                              CONSTRAINT pk_query_history PRIMARY KEY,
    conversation_id       VARCHAR2(100) NOT NULL,
    turn_id               NUMBER        NOT NULL,
    user_query            CLOB          NOT NULL,
    interpreted_intent    JSON,
    retrieval_mode        VARCHAR2(10),             -- SQL | VECTOR | HYBRID
    generated_sql         CLOB,
    result_paper_ids      JSON,
    clarification_question VARCHAR2(1000 CHAR),
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ── query_executions (per-attempt audit log) ─────────────────────────────────
CREATE TABLE query_executions (
    execution_id               NUMBER GENERATED BY DEFAULT AS IDENTITY
                                   CONSTRAINT pk_query_executions PRIMARY KEY,
    history_id                 NUMBER        NOT NULL,
    attempt_number             NUMBER        NOT NULL,
    sql_text                   CLOB          NOT NULL,
    bind_params                JSON,
    status                     VARCHAR2(10)  NOT NULL,   -- SUCCESS | FAILED
    error_code                 VARCHAR2(20),
    error_message              VARCHAR2(2000 CHAR),
    error_category             VARCHAR2(30),
    row_count                  NUMBER,
    execution_time_ms          NUMBER,
    corrected_from_execution_id NUMBER,
    created_at                 TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ── experiment_results ───────────────────────────────────────────────────────
CREATE TABLE experiment_results (
    result_id              NUMBER GENERATED BY DEFAULT AS IDENTITY
                               CONSTRAINT pk_experiment_results PRIMARY KEY,
    experiment_name        VARCHAR2(100) NOT NULL,
    run_id                 VARCHAR2(100) NOT NULL,
    configuration          JSON          NOT NULL,
    metric_name            VARCHAR2(100) NOT NULL,
    metric_value           BINARY_DOUBLE NOT NULL,
    dataset_version        VARCHAR2(50),
    is_synthetic_smoke_test NUMBER(1) DEFAULT 0 NOT NULL,
    created_at             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

