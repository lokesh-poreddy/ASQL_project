"""SQL validator: multi-stage safety check before execution.

Stages:
  1. Non-empty check
  2. SELECT-only enforcement
  3. Forbidden keyword scan (DDL / DCL / dangerous DML)
  4. Multi-statement prevention
  5. Parenthesis balance check
  6. Schema column existence check (optional, requires SchemaSnapshot)

All stages must pass before the executor is called.
"""
from __future__ import annotations

import re

from app.common.exceptions import SQLValidationError
from app.common.logging import get_logger

logger = get_logger("sql.validator")

FORBIDDEN_TOKENS: tuple[str, ...] = (
    "DROP ",
    "TRUNCATE ",
    "ALTER ",
    "GRANT ",
    "REVOKE ",
    "CREATE ",
    "DELETE ",
    "UPDATE ",
    "INSERT ",
    "MERGE ",
    "EXECUTE ",
    "EXEC ",
    "CALL ",
    "DBMS_",
    "UTL_",
    "SYS.",
    "SYSTEM.",
)

# Only these Oracle table aliases are allowed in queries generated by our code
ALLOWED_FROM_TABLES = frozenset({
    "papers", "authors", "venues", "research_areas", "keywords",
    "paper_authors", "paper_keywords", "citations",
    "paper_embeddings", "query_history", "query_executions",
    "experiment_results",
    # Views
    "v_paper_full", "v_paper_summary", "v_paper_authors_agg",
    "v_paper_keywords_agg", "v_research_area_catalog",
    # Materialized views
    "mv_research_area_stats", "mv_venue_stats",
})


class SQLValidator:

    def validate(self, sql: str, *, strict: bool = True) -> None:
        """Validate the SQL string. Raises SQLValidationError on any failure.

        strict=False skips the allowed-table check (used for EXPLAIN queries).
        """
        errors: list[str] = []
        normalized = re.sub(r"\s+", " ", sql.strip().upper())

        if not normalized:
            raise SQLValidationError("SQL query is empty.", errors=["Empty query."])

        # Stage 1: SELECT-only
        if not normalized.startswith("SELECT"):
            errors.append("Only SELECT statements are permitted.")

        # Stage 2: Forbidden tokens
        for token in FORBIDDEN_TOKENS:
            if token in normalized:
                errors.append(f"Forbidden SQL token: '{token.strip()}'")

        # Stage 3: Multiple statements (naive check — semicolon in middle)
        stripped = normalized.rstrip(";")
        if ";" in stripped:
            errors.append("Multiple SQL statements are not permitted.")

        # Stage 4: Parenthesis balance
        if normalized.count("(") != normalized.count(")"):
            errors.append("Unbalanced parentheses.")

        # Stage 5: Comment-based SQL injection vectors
        if "--" in sql or "/*" in sql:
            errors.append("SQL comments are not permitted in generated queries.")

        if errors:
            raise SQLValidationError(
                f"SQL validation failed ({len(errors)} error(s)): {errors[0]}",
                errors=errors,
            )

        logger.debug("SQL validation passed for query starting with: %s", sql[:60])
